const f = (at: Date) => `<t:${Math.floor(at.getTime() / 1000)}:f>`;
const why = (labels: { punishment: string; reason: string; issued: string; evidence: string; none: string }) =>
  (typeLabel: string, reason: string, evidence: string[], issuedAt?: Date) =>
    [
      `**${labels.punishment}:** ${typeLabel}`,
      `**${labels.reason}:** ${reason}`,
      issuedAt ? `**${labels.issued}:** ${f(issuedAt)}` : null,
      "",
      evidence.length ? `**${labels.evidence}:**\n${evidence.join("\n")}` : `**${labels.evidence}:** ${labels.none}`,
    ].filter((l): l is string => l !== null).join("\n");

